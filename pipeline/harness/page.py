"""The last step of a job: turn its section files into one chapter page.

    sources/jobs/<id>/page/chapter.yaml      page chrome (title, lede from the plan's chapter summary, shell)
    sources/jobs/<id>/page/sections/*.md     the written sections, in order, tidied for the builder
    sources/jobs/<id>/page/files/*           every listing the sections can show or run
    sources/jobs/<id>/page/dist/index.html   tools/build.mjs output: one self-contained page, plus the paged build
                                             (parts/, assets/, manifest.json, search.json) the app reads from
    sources/jobs/<id>/page/build.json        what the build reported

Tidying, so independently written sections build as one page:
  - a chunk that continues the previous chunk's section (a long section split in two) is appended to it,
    instead of opening a second section with the same id
  - titles lose a leading number ("14.1 Introducing ReplicaSets"): the page prints the id itself
  - `pages:` is dropped: writers sometimes invent it, and the page shows it as a source reference
This is also the first check across sections: duplicate ids, links to other sections, one shell for the page.
"""
from __future__ import annotations

import html
import json
import re
import shutil
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
NUMBER = re.compile(r"^\s*\d+(?:\.\d+)*\.?\s+")


def split_section(text: str) -> tuple[dict, str]:
    m = re.match(r"^---\n([\s\S]*?)\n---\n?", text)
    if not m:
        return {}, text
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        meta = {}
    return (meta if isinstance(meta, dict) else {}), text[m.end():]


def tidy_sections(texts: list[str]) -> list[tuple[dict, str]]:
    out: list[tuple[dict, str]] = []
    for text in texts:
        meta, body = split_section(text)
        sid = str(meta.get("id", "")).strip()
        if out and sid and sid == str(out[-1][0].get("id")):
            prev_meta, prev_body = out[-1]
            out[-1] = (prev_meta, prev_body.rstrip() + "\n\n" + body.lstrip())
            continue
        meta = {k: v for k, v in meta.items() if k != "pages"}
        if meta.get("title"):
            meta["title"] = NUMBER.sub("", str(meta["title"])).strip() or str(meta["title"])
        meta["id"] = sid
        out.append((meta, body))
    return out


def run_chapter_id(spec: dict) -> str:
    """How a run is addressed in the library: chapter number plus the job id's random tail, '14-8a8c'."""
    return f"{spec.get('chapter_id') or 'ch'}-{str(spec.get('id', ''))[-4:]}"


def book_name(upload_name: str) -> str:
    """'Kubernetes in Action, Second Edition ... (Marko Lukša, Kevin Conner) (z-lib.sk)-493-593.pdf' -> 'Kubernetes in Action'."""
    name = re.sub(r"\.pdf$", "", upload_name, flags=re.I)
    name = re.sub(r"\([^)]*\)", " ", name)
    name = re.sub(r"[-_\s]+\d+[-_]\d+\s*$", "", name)
    name = re.sub(r"\s+", " ", name).strip(" -_,")
    short = re.split(r",\s|\s[-–:]\s|:\s", name, maxsplit=1)[0].strip()
    return short if len(short) >= 6 else (name[:60] or "Uploaded document")


def build_page(job: Path) -> dict:
    spec = json.loads((job / "job.json").read_text(encoding="utf-8"))
    chapter = json.loads((job / "chapter.json").read_text(encoding="utf-8"))
    plan = json.loads((job / "plan.json").read_text(encoding="utf-8")) if (job / "plan.json").exists() else {}
    page = job / "page"
    if page.exists():
        shutil.rmtree(page)
    (page / "sections").mkdir(parents=True)
    (page / "files").mkdir()

    for f in sorted((job / "sections").glob("*/files/*")):  # every chunk's listings; same name = same listing
        if f.is_file():
            shutil.copy(f, page / "files" / f.name)
    texts = [p.read_text(encoding="utf-8") for p in sorted((job / "chapter").glob("*.md"))]
    sections = tidy_sections(texts)
    for i, (meta, body) in enumerate(sections, 1):
        front = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True).strip()
        slug = re.sub(r"[^a-z0-9]+", "-", meta["id"].lower()).strip("-") or str(i)
        (page / "sections" / f"{i:02d}-{slug}.md").write_text(f"---\n{front}\n---\n{body.rstrip()}\n", encoding="utf-8")

    title = NUMBER.sub("", chapter.get("title", "")) or spec.get("chapter_title", "Chapter")
    book = book_name(spec.get("file", ""))
    chrome = {
        "id": f"ch{chapter.get('id', '')}",
        "title": f"{title} · {book}",
        "brand_mark": "r",
        "brand_sub": book,
        "eyebrow": f"Chapter {chapter.get('id', '')} · written by the readlab pipeline",
        "headline": html.escape(title),
        "lede": html.escape(str(plan.get("chapter_summary") or "")),
        "footer": "Generated by readlab from an uploaded PDF: the author's ideas retold in new words, checked against "
                  "the source. Read the book for the original.",
        "shell": {"plugin": "basic", "user": "you@book", "dir": "~"},
    }
    (page / "chapter.yaml").write_text(yaml.safe_dump(chrome, sort_keys=False, allow_unicode=True), encoding="utf-8")

    # the validator's safe fixes over the assembled page (jobs from before the scorer kept them), plus its report
    extract = next(iter(sorted((job / "ingest").glob("*/extract.json"))), None)
    subprocess.run(["node", str(ROOT / "tools" / "validate.mjs"), str(page), "--fix", "--json", str(page / "validate.json"),
                    *(["--source", str(extract)] if extract else [])], capture_output=True, text=True, timeout=120, cwd=ROOT)
    proc = subprocess.run(["node", str(ROOT / "tools" / "build.mjs"), str(page), "--out", str(page / "dist"), "--allow-errors", "--split"],
                          capture_output=True, text=True, timeout=120, cwd=ROOT)
    lines = [l for l in proc.stderr.splitlines() if l.strip()]
    errors = [l for l in lines if not l.startswith("warning:") and "nothing written" not in l]
    report = {"ok": proc.returncode == 0 and (page / "dist" / "index.html").is_file(), "sections": len(sections),
              "files": len(list((page / "files").iterdir())), "errors": errors,
              "warnings": [l[len("warning: "):] for l in lines if l.startswith("warning:")], "summary": proc.stdout.strip()}
    (page / "build.json").write_text(json.dumps(report, indent=1, ensure_ascii=False), encoding="utf-8")
    return report


if __name__ == "__main__":  # rebuild the page of finished jobs:  ./run.sh python -m pipeline.harness.page <job-dir>...
    import sys

    for arg in sys.argv[1:]:
        r = build_page(Path(arg))
        print(arg, "ok" if r["ok"] else "FAILED", f"{r['sections']} sections, {len(r['errors'])} errors", *r["errors"][:5], sep="\n  ")
