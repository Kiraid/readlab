#!/usr/bin/env node
// Build the catalog page: every widget's example.yaml plus sample flow and sequence diagrams, as one
// chapter. It is the visual check for the engine and the reference page for what the catalog can do.
//
//   node tools/catalog.mjs [--out runs/catalog]
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildChapter } from './build.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));

const DIAGRAMS = `---
id: "0.1"
title: Diagrams
---
A flow diagram with a group, a journey and steps. Nothing here is positioned by hand.

:::diagram flow
nodes:
  user: client@0,1 "browser"
  lb: gateway@1,1 "load balancer" "203.0.113.10"
  app1: worker@2,0 "app server 1"
  app2: worker@2,2 "app server 2"
  cache: cache@3,0 "cache"
  db: datastore@3,2 "database" "primary"
groups:
  dc: { nodes: [lb, app1, app2, cache, db], label: data centre }
edges:
  - user > lb flow "HTTPS"
  - lb > app1 edge "round robin"
  - lb > app2 edge
  - app1 > cache edge "hit?"
  - app1 > db dim "on a miss"
  - app2 > db edge "SQL"
journeys:
  - user > lb > app1 > cache
steps:
  - user, user>lb: The browser connects to the load balancer's public address.
  - lb, lb>app1, lb>app2: The balancer hands each new connection to the next app server.
  - app1>cache, cache: App server 1 checks the cache first.
  - app1>db, app2>db, db: Misses and writes go to the database.
caption: A request path with a cache in front of the database.
:::

A sequence diagram; \`steps: auto\` turns every message into a step.

:::diagram sequence
participants:
  c: client "resolver"
  root: external "root server"
  tld: external ".com server"
  auth: service "example.com NS"
messages:
  - c > root: where is www.example.com?
  - root --> c: ask the .com servers
  - c > tld: where is www.example.com?
  - tld --> c: ask example.com's name server
  - c > auth: where is www.example.com?
  - auth --> c: 93.184.215.14
  - note c: caches the answer for its TTL
steps: auto
caption: Iterative DNS resolution.
:::
`;

export function catalogChapter(dir) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, 'sections'), { recursive: true });
  writeFileSync(join(dir, 'chapter.yaml'), [
    'id: catalog', 'title: Engine catalog', 'brand_sub: every widget and diagram', 'eyebrow: Generated by tools/catalog.mjs',
    'headline: The <span>catalog.</span>', 'lede: Each widget rendered from its own example.yaml, plus the diagram renderer.',
    'footer: Generated page; examples are written for this repo.', 'shell: { plugin: basic, user: you@book, dir: "~" }', '',
  ].join('\n'));
  writeFileSync(join(dir, 'sections', '00-diagrams.md'), DIAGRAMS);
  const widgets = readdirSync(join(ROOT, 'engine', 'widgets')).filter((w) => existsSync(join(ROOT, 'engine', 'widgets', w, 'example.yaml'))).sort();
  widgets.forEach((w, i) => {
    const example = readFileSync(join(ROOT, 'engine', 'widgets', w, 'example.yaml'), 'utf8').trim();
    writeFileSync(join(dir, 'sections', `${String(i + 1).padStart(2, '0')}-${w}.md`),
      `---\nid: "1.${i + 1}"\ntitle: ${w}\n---\nFrom \`engine/widgets/${w}/example.yaml\`.\n\n:::widget ${w}\n${example}\n:::\n`);
  });
  return widgets;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const oi = args.indexOf('--out');
  const out = resolve(oi >= 0 ? args[oi + 1] : join(ROOT, 'runs', 'catalog'));
  const src = join(out, 'src');
  const widgets = catalogChapter(src);
  const res = buildChapter(src);
  for (const e of res.errors) console.error(`${e.file}${e.line ? `:${e.line}` : ''}: ${e.message}`);
  writeFileSync(join(out, 'index.html'), res.html);
  console.log(`catalog: ${widgets.length} widgets + diagrams -> ${join(out, 'index.html')}${res.errors.length ? ` (${res.errors.length} errors)` : ''}`);
  process.exit(res.errors.length ? 1 : 0);
}
